// Copies the structured-output schemas out of ../app.html into src/schemas.js,
// so the Worker accepts exactly the schemas the app sends and never drifts from it.
// Runs before `npm run dev`, `npm test` and `npm run deploy`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = dirname(fileURLToPath(import.meta.url));
const appPath = join(here, "..", "..", "app.html");
const outPath = join(here, "..", "src", "schemas.js");
const NAMES = ["gaps", "diagnostic", "bridge", "minicheck", "lesson"];
const MARKER = "// JSON schemas for the API's structured output.";

function die(msg) {
  console.error(`extract-schemas: ${msg}`);
  process.exit(1);
}

// Index just past the brace that closes the one at `open`, skipping string and comment contents.
function matchBrace(src, open) {
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    const c = src[i];
    if (c === '"' || c === "'" || c === "`") {
      for (i++; i < src.length && src[i] !== c; i++) if (src[i] === "\\") i++;
    } else if (c === "/" && src[i + 1] === "/") {
      i = src.indexOf("\n", i);
      if (i === -1) return -1;
    } else if (c === "/" && src[i + 1] === "*") {
      i = src.indexOf("*/", i + 2);
      if (i === -1) return -1;
      i++;
    } else if (c === "{") depth++;
    else if (c === "}" && --depth === 0) return i + 1;
  }
  return -1;
}

const html = readFileSync(appPath, "utf8");
const start = html.indexOf(MARKER);
if (start === -1) die(`could not find the marker comment in ${appPath}`);
if (html.indexOf(MARKER, start + 1) !== -1) die("the marker comment appears more than once");
const decl = html.indexOf("const SCHEMA = {", start);
if (decl === -1) die("could not find `const SCHEMA = {` after the marker comment");
const end = matchBrace(html, html.indexOf("{", decl));
if (end === -1) die("could not find the end of the SCHEMA object");
const block = html.slice(start, end);

let schemas;
try {
  // Evaluated in an empty context: the block only builds plain objects.
  schemas = vm.runInNewContext(`(() => { ${block}; return SCHEMA; })()`, Object.create(null), { timeout: 1000 });
  schemas = JSON.parse(JSON.stringify(schemas)); // plain JSON, no shared references
} catch (e) {
  die(`could not evaluate the schema block: ${e.message}`);
}

const keys = Object.keys(schemas || {}).sort();
if (keys.join(",") !== [...NAMES].sort().join(",")) die(`expected schemas ${NAMES.join(", ")}, found ${keys.join(", ") || "none"}`);
for (const name of NAMES) {
  const s = schemas[name];
  if (!s || s.type !== "object" || typeof s.properties !== "object") die(`schema "${name}" is not an object schema`);
}

const ordered = Object.fromEntries(NAMES.map((n) => [n, schemas[n]]));
const out = `// GENERATED by scripts/extract-schemas.mjs from ../app.html. Do not edit by hand:
// run \`npm run extract\` (dev, test and deploy run it for you).
export const SCHEMAS = ${JSON.stringify(ordered, null, 2)};
`;
let previous = "";
try { previous = readFileSync(outPath, "utf8"); } catch { /* first run */ }
if (previous !== out) writeFileSync(outPath, out);
console.log(`extract-schemas: ${NAMES.length} schemas ${previous === out ? "unchanged" : "written to src/schemas.js"}`);
